#!/usr/bin/env python3
"""Compile explicitly selected exports into redacted, reviewed practice proposals.

Python 3.9+ standard library. No discovery, network, model, subprocess, or installer.
The CLI checks declared records. It cannot authenticate the person who consented.
"""
import argparse
import copy
import datetime as dt
import hashlib
import json
import os
from pathlib import Path
import re
import shlex
import stat
import sys
import tempfile
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

VERSION = 1
MAX_CONTROL = 2 * 1024 * 1024
MAX_CASEBOOK = 32 * 1024 * 1024
CLASSES = {'user-session', 'neutral-export', 'automation', 'subagent', 'synthetic'}
KINDS = ('repeated-task', 'recurring-feedback', 'follow-up-instruction',
         'command-failure', 'executed-command', 'repeated-repair',
         'missed-tool', 'cost-decision', 'user-method')
DIGEST = re.compile(r'^[a-f0-9]{64}$')
SLUG = re.compile(r'^[a-z][a-z0-9-]{0,63}$')
UTC = dt.timezone.utc
MARKERS = re.compile(r'(\[(?:PRIVATE|SECRET|URL|EMAIL|PATH|IDENTIFIER|NUMBER|LONG-TOKEN)\])')  # Redactor output
# Known host-injected user wrappers. They are context, not attributable human feedback.
INJECTED_PREFIXES = (
    '<recommended_plugins>', '# agents.md instructions', '<environment_context>',
    '<app-context>', '<in-app-browser-context', '<skill>', '<codex_internal_context',
    '# applications mentioned by the user:', '<command-name>', '<command-message>',
    '<local-command-stdout', '<system-reminder>', '<task-notification',
    'caveat: the messages below were generated',
)


class Fault(Exception):
    def __init__(self, code):
        self.code = code


def require(condition, code):
    if not condition:
        raise Fault(code)


def canonical(value):
    return json.dumps(value, sort_keys=True, ensure_ascii=True, separators=(',', ':'), allow_nan=False).encode('utf-8')


def digest(value):
    return hashlib.sha256(value if isinstance(value, bytes) else canonical(value)).hexdigest()


def ident(prefix, value):
    return prefix + digest(value)[:24]


def pairs(items):
    result = {}
    for key, value in items:
        require(key not in result, 'duplicate_json_key')
        result[key] = value
    return result


def decode(data):
    try:
        return json.loads(data.decode('utf-8'), object_pairs_hook=pairs,
                          parse_constant=lambda _: (_ for _ in ()).throw(Fault('nonfinite_json')))
    except (UnicodeError, ValueError, RecursionError):
        raise Fault('invalid_json_or_encoding')


def keys(obj, required, optional=()):
    require(isinstance(obj, dict), 'expected_object')
    require(set(required) <= set(obj) <= set(required) | set(optional), 'invalid_record_fields')


def slug(value):
    require(isinstance(value, str) and SLUG.fullmatch(value), 'invalid_alias')
    return value


def text(value, maxlen=6000):
    require(isinstance(value, str) and 0 < len(value.strip()) <= maxlen, 'invalid_text')
    return value.strip()


class Redactor:
    """One output boundary; unknown secrets still require human privacy review."""
    def __init__(self, terms=()):
        self.terms = sorted((x for x in terms if isinstance(x, str) and x), key=len, reverse=True)

    def clean(self, value):
        if isinstance(value, str):
            if DIGEST.fullmatch(value) or re.fullmatch(r'(?:[epnslc]|scope)-[a-f0-9]{24}', value):
                return value
            # Whole sensitive spans first: a declared term must not erase the label (secret=, PRIVATE KEY,
            # a mail domain) that lets these patterns remove the value.
            value = re.sub(r'-----BEGIN [^-\n]*(?:PRIVATE KEY|CERTIFICATE)-----.*?-----END [^-\n]+-----', '[SECRET]', value, flags=re.S)
            value = re.sub(r'(?i)\b(?:password|passwd|secret|api[_-]?key|access[_-]?token|authorization|bearer|token)\s*[:= ]\s*["\']?[^\s,;"\']+', '[SECRET]', value)
            value = re.sub(r'\b(?:sk-[A-Za-z0-9_-]{8,}|gh[pousr]_[A-Za-z0-9_]{8,}|AKIA[A-Z0-9]{12,})\b', '[SECRET]', value)
            value = re.sub(r'https?://[^\s<>"\']+', '[URL]', value)
            value = re.sub(r'[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}', '[EMAIL]', value)
            value = re.sub(r'(?:[A-Za-z]:[\\/]|(?<!\w)/|~/)[^\s<>"\']+', '[PATH]', value)
            value = re.sub(r'\b\d{3}-\d{2}-\d{4}\b', '[IDENTIFIER]', value)
            value = re.sub(r'(?<!\w)(?:\+?\d[ ()-]*){10,19}(?!\w)', '[NUMBER]', value)
            # Digests/opaque IDs generated by this program remain verifiable.
            value = re.sub(r'\b[A-Za-z0-9_+=-]{32,}\b', lambda m: m.group(0) if DIGEST.fullmatch(m.group(0)) or re.fullmatch(r'[a-z-]+', m.group(0)) else '[LONG-TOKEN]', value)
            for term in self.terms:
                # Case variants of a declared term are the same term. Generated markers are never rewritten,
                # so cleaning stays idempotent when a term such as "private" or "secret" occurs inside one.
                parts = MARKERS.split(value)
                parts[::2] = [re.sub(re.escape(term), '[PRIVATE]', part, flags=re.I) for part in parts[::2]]
                value = ''.join(parts)
            value = ''.join(c if c in '\n\t' or ord(c) >= 32 else ' ' for c in value)
            return value[:12000]
        if isinstance(value, dict):
            return {k: self.clean(v) for k, v in value.items()}
        if isinstance(value, list):
            return [self.clean(x) for x in value]
        return value


def restricted(path):
    return any(part in {'.codex', '.claude', '.ssh', '.aws', '.gnupg'} for part in path.parts)


def declared_target(value):
    """A declared target may reach its directory through a parent alias (macOS /tmp, /var); its final component
    must be the file itself, not another link."""
    if not isinstance(value, str) or not os.path.isabs(value):
        return None
    path = Path(value)
    return None if path.is_symlink() else path.parent.resolve() / path.name


def selected_path(raw, base, resolved_path=None):
    require(isinstance(raw, str) and raw and '\x00' not in raw and '~' not in raw, 'invalid_path')
    path = Path(raw)
    if not path.is_absolute():
        path = base / path
    require(not restricted(path), 'restricted_source')
    try:
        resolved = path.resolve(strict=True)
        require(not restricted(resolved), 'restricted_source')
        # Explicit links require their exact target to already be disclosed in the private manifest.
        lexical = Path(os.path.abspath(str(path)))
        explicit_link = path.is_symlink()
        if explicit_link:
            require(declared_target(resolved_path) == resolved, 'symlink_target_not_declared')
        elif resolved_path is not None:
            require(declared_target(resolved_path) == resolved, 'resolved_target_mismatch')
        require(stat.S_ISREG(resolved.stat().st_mode), 'not_regular_file')
        return resolved, explicit_link
    except (OSError, RuntimeError, ValueError):
        raise Fault('source_unavailable')


def snapshot(path, limit):
    try:
        with path.open('rb') as handle:
            before = os.fstat(handle.fileno())
            require(stat.S_ISREG(before.st_mode), 'not_regular_file')
            require(before.st_size <= limit, 'file_budget_exceeded')
            data = handle.read(limit + 1)
            after = os.fstat(handle.fileno())
        current = path.stat()
        attrs = ('st_dev', 'st_ino', 'st_size', 'st_mtime_ns', 'st_ctime_ns')
        require(all(getattr(before, a) == getattr(after, a) == getattr(current, a) for a in attrs),
                'source_changed_during_read')
        require(len(data) <= limit and len(data) == before.st_size, 'file_budget_exceeded')
        return data
    except OSError:
        raise Fault('source_unavailable')


def control(path, limit=MAX_CONTROL):
    resolved, _ = selected_path(path, Path.cwd())
    data = snapshot(resolved, limit)
    return decode(data), data, resolved


def moment(value, zone):
    if not isinstance(value, str) or 'T' not in value:
        return None
    try:
        parsed = dt.datetime.fromisoformat(value.replace('Z', '+00:00'))
        if parsed.tzinfo is None:
            first, second = parsed.replace(tzinfo=zone, fold=0), parsed.replace(tzinfo=zone, fold=1)
            if first.utcoffset() != second.utcoffset():
                return None  # Ambiguous or nonexistent local wall time.
            if first.astimezone(UTC).astimezone(zone).replace(tzinfo=None) != parsed:
                return None
            parsed = first
        return parsed.astimezone(UTC)
    except (ValueError, OverflowError):
        return None


def stamp(value):
    return value.astimezone(UTC).isoformat().replace('+00:00', 'Z')


def load_manifest(path):
    manifest, _, resolved = control(path)
    keys(manifest, ('schema_version', 'corpus_id', 'access', 'window', 'included_classes', 'budgets', 'sources'),
         ('destinations', 'private_terms'))
    require(manifest['schema_version'] == VERSION, 'unsupported_schema')
    slug(manifest['corpus_id'])
    keys(manifest['access'], ('basis', 'reference'))
    require(manifest['access']['basis'] == 'user-selected-export', 'explicit_export_access_required')
    text(manifest['access']['reference'], 200)
    keys(manifest['window'], ('start', 'end', 'timezone'))
    try:
        zone = ZoneInfo(manifest['window']['timezone'])
        start = dt.date.fromisoformat(manifest['window']['start'])
        end = dt.date.fromisoformat(manifest['window']['end'])
        require(start <= end, 'invalid_window')
        begin = dt.datetime.combine(start, dt.time.min, zone).astimezone(UTC)
        finish = dt.datetime.combine(end + dt.timedelta(days=1), dt.time.min, zone).astimezone(UTC)
    except (ValueError, TypeError, KeyError, ZoneInfoNotFoundError, OverflowError):
        raise Fault('invalid_window_or_timezone')
    classes = manifest['included_classes']
    require(isinstance(classes, list) and classes and len(classes) == len(set(classes)) and set(classes) <= CLASSES,
            'invalid_source_classes')
    budgets = manifest['budgets']
    keys(budgets, ('max_files', 'max_file_bytes', 'max_total_bytes', 'max_line_bytes', 'max_events'))
    ceilings = {'max_files': 256, 'max_file_bytes': 16 * 1024 * 1024, 'max_total_bytes': 64 * 1024 * 1024,
                'max_line_bytes': 1024 * 1024, 'max_events': 50000}
    for key, ceiling in ceilings.items():
        require(type(budgets[key]) is int and 1 <= budgets[key] <= ceiling, 'invalid_budget')
    sources, destinations = manifest['sources'], manifest.get('destinations', [])
    require(isinstance(sources, list) and sources and isinstance(destinations, list), 'invalid_sources')
    require(len(sources) + len(destinations) <= budgets['max_files'], 'file_count_budget_exceeded')
    terms = manifest.get('private_terms', [])
    require(isinstance(terms, list) and len(terms) <= 128, 'invalid_private_terms')
    for term in terms:
        text(term, 1000)
        require(len(term) >= 4 and not DIGEST.fullmatch(term) and not re.fullmatch(r'[epnsc]-[0-9a-f]{24}', term), 'private_term_too_short_or_structural')
    redactor = Redactor(terms)
    aliases = set()
    for src in sources:
        keys(src, ('alias', 'path', 'adapter', 'source_class', 'lineage_id', 'session_id'), ('mirrors', 'resolved_path'))
        slug(src['alias']); slug(src['lineage_id']); text(src['session_id'], 500)
        require(src['adapter'] in {'codex', 'claude', 'neutral', 'design'}, 'unsupported_adapter')
        require(src['source_class'] in CLASSES, 'invalid_source_class')
        require(src['alias'] not in aliases and redactor.clean(src['alias']) == src['alias'], 'duplicate_or_private_alias')
        aliases.add(src['alias'])
        mirrors = src.get('mirrors', [])
        require(isinstance(mirrors, list) and len(mirrors) <= budgets['max_events'], 'invalid_mirrors')
        seen = set()
        for mirror in mirrors:
            keys(mirror, ('event_id', 'source_alias', 'target_event_id'))
            text(mirror['event_id'], 500); text(mirror['target_event_id'], 500); slug(mirror['source_alias'])
            require(mirror['event_id'] not in seen, 'duplicate_mirror')
            seen.add(mirror['event_id'])
    for dst in destinations:
        keys(dst, ('alias', 'path'), ('resolved_path',))
        slug(dst['alias'])
        require(dst['alias'] not in aliases and redactor.clean(dst['alias']) == dst['alias'], 'duplicate_or_private_alias')
        aliases.add(dst['alias'])
    return manifest, resolved.parent, zone, begin, finish, redactor


def unquoted(value):
    """Conservative: quoted/code-only material never becomes a user-method signal."""
    if not isinstance(value, str):
        return ''
    value = re.sub(r'```.*?```', '', value, flags=re.S)
    value = re.sub(r'`[^`]*`', '', value)
    value = re.sub(r'<(?:system|instructions|environment_context|tool_result|transcript_evidence)[^>]*>.*?</[^>]+>', '', value, flags=re.S | re.I)
    value = re.sub(r'"[^"\n]*"|“[^”\n]*”', '', value)
    return '\n'.join(line for line in value.splitlines() if not line.lstrip().startswith(('>', 'Quoted:', 'Quote:'))).strip()


def command_name(tool, command):
    known_tools = {'Bash', 'bash', 'shell', 'exec_command', 'shell_command', 'functions.exec_command', 'functions.shell'}
    if tool not in known_tools or not isinstance(command, str):
        return None
    try:
        parts = shlex.split(command)
        first = parts[0] if parts else ''
        while '=' in first and len(parts) > 1:
            parts.pop(0); first = parts[0]
        name = first.replace('\\', '/').rsplit('/', 1)[-1]
        return name if re.fullmatch(r'[A-Za-z][A-Za-z0-9_.-]{0,39}', name) else 'command'
    except ValueError:
        return 'command'


def outcome(value, explicit=None):
    if explicit in {'success', 'failure'}:
        return explicit
    if isinstance(value, dict):
        code = value.get('exit_code', value.get('returncode'))
        if type(code) is int:
            return 'success' if code == 0 else 'failure'
        value = value.get('output', '')
    if isinstance(value, str):
        try:
            nested = decode(value.encode())
            if isinstance(nested, dict):
                return outcome(nested)
        except Fault:
            pass
        match = re.search(r'(?:Process exited with code|exit[_ ]code\s*[:=]?)\s*(-?\d+)', value, flags=re.I)
        if match:
            return 'success' if int(match.group(1)) == 0 else 'failure'
    return 'unknown'


def extract(src, data, max_line):
    """Decode only documented event positions. Return transient raw events, never raw output."""
    adapter = src['adapter']
    if adapter in {'neutral', 'design'}:
        obj = decode(data)
        field = 'events' if adapter == 'neutral' else 'records'
        keys(obj, ('schema_version', field))
        require(obj['schema_version'] == (1 if adapter == 'neutral' else '1.0') and isinstance(obj[field], list), 'unsupported_neutral_schema')
        records = list(enumerate(obj[field], 1))
    else:
        records = []
        for line, raw in enumerate(data.splitlines(), 1):
            require(len(raw) <= max_line, 'line_budget_exceeded')
            if raw.strip():
                records.append((line, decode(raw)))
    events = []
    ignored = 0
    injected_context = 0
    session = src['session_id']
    for line, row in records:
        require(isinstance(row, dict), 'unsupported_scalar_record')
        if adapter == 'codex' and row.get('type') == 'session_meta':
            payload = row.get('payload', {})
            require(isinstance(payload, dict), 'invalid_codex_record')
            session = str(payload.get('id', session)); ignored += 1
            continue
        timestamp = row.get('timestamp')
        raw_id = row.get('id', row.get('uuid'))
        items = []
        if adapter == 'design':
            keys(row, ('source_type', 'fingerprint', 'created_at', 'project_id', 'signal_class', 'summary'), ('impact', 'method'))
            require(row['source_type'] == 'design-neutral-export' and isinstance(row['fingerprint'], str) and DIGEST.fullmatch(row['fingerprint']), 'invalid_design_fingerprint')
            require(isinstance(row['project_id'], str) and re.fullmatch(r'project-[a-f0-9]{20}', row['project_id']), 'invalid_design_project')
            labels = {'feedback': 'recurring-feedback', 'friction': 'recurring-feedback', 'repair': 'repeated-repair',
                      'missed-tool': 'missed-tool', 'cost-decision': 'cost-decision', 'user-method': 'user-method'}
            require(row['signal_class'] in labels, 'invalid_design_signal')
            parts = [text(row['summary'])]
            for field in ('impact', 'method'):
                if field in row:
                    parts.append(field.title() + ': ' + text(row[field]))
            timestamp = row['created_at']
            items = [{'actor': 'reported', 'kind': 'reported_summary', 'text': ' '.join(parts),
                      'session': row['project_id'], 'native_id': row['fingerprint'],
                      'declared_signal': labels[row['signal_class']], 'origin_fingerprint': row['fingerprint']}]
        elif adapter == 'neutral':
            keys(row, ('id', 'session_id', 'timestamp', 'actor', 'kind'),
                 ('text', 'tool', 'command', 'call_id', 'outcome'))
            require(row['actor'] in {'user', 'assistant', 'tool'} and row['kind'] in {'message', 'tool_call', 'tool_result'},
                    'unsupported_neutral_event')
            require(row['kind'] != 'tool_result' or row['actor'] == 'tool', 'invalid_tool_actor')
            require(row['kind'] != 'tool_call' or row['actor'] == 'assistant', 'invalid_tool_actor')
            if row['kind'] != 'message':
                text(row.get('call_id'), 500)
            if 'outcome' in row:
                require(row['outcome'] in {'success', 'failure', 'unknown'}, 'invalid_outcome')
            text(row['id'], 500); text(row['session_id'], 500)
            items = [dict(row, session=row['session_id'], native_id=row['id'])]
        elif adapter == 'codex':
            payload = row.get('payload')
            require(isinstance(payload, dict), 'invalid_codex_record')
            typ = payload.get('type')
            raw_id = raw_id or payload.get('id')
            if row.get('type') == 'response_item' and typ == 'message':
                actor = payload.get('role')
                if actor in {'user', 'assistant'}:
                    content = payload.get('content', [])
                    require(isinstance(content, list), 'invalid_codex_content')
                    strings = [x['text'] for x in content if isinstance(x, dict) and x.get('type') in {'input_text', 'output_text'} and isinstance(x.get('text'), str)]
                    items = [{'actor': actor, 'kind': 'message', 'text': '\n'.join(strings)}]
            elif row.get('type') == 'event_msg' and typ in {'user_message', 'agent_message'}:
                items = [{'actor': 'user' if typ == 'user_message' else 'assistant', 'kind': 'message', 'text': payload.get('message', '')}]
            elif row.get('type') == 'response_item' and typ in {'function_call', 'custom_tool_call'}:
                args = payload.get('arguments', payload.get('input', {}))
                if isinstance(args, str):
                    try:
                        args = decode(args.encode())
                    except Fault:
                        args = {'command': args}
                if not isinstance(args, dict):
                    args = {}
                items = [{'actor': 'assistant', 'kind': 'tool_call', 'tool': payload.get('name', ''),
                          'command': args.get('cmd', args.get('command', '')), 'call_id': payload.get('call_id'), 'text': ''}]
            elif row.get('type') == 'response_item' and typ in {'function_call_output', 'custom_tool_call_output'}:
                items = [{'actor': 'tool', 'kind': 'tool_result', 'call_id': payload.get('call_id'),
                          'outcome': outcome(payload.get('output')), 'text': ''}]
            elif row.get('type') == 'response_item' and typ not in {'reasoning', 'compaction'}:
                raise Fault('unsupported_codex_event')
            elif row.get('type') == 'event_msg' and typ not in {'token_count', 'task_started', 'task_complete', 'task_completed', 'turn_aborted', 'context_compacted', 'exec_command_begin', 'exec_command_end'}:
                raise Fault('unsupported_codex_event')
            elif row.get('type') not in {'response_item', 'event_msg', 'turn_context'}:
                raise Fault('unsupported_codex_record')
        else:
            if row.get('isMeta') or row.get('isSidechain') and src['source_class'] != 'subagent':
                ignored += 1
                continue
            typ = row.get('type')
            if typ in {'user', 'assistant'}:
                msg = row.get('message')
                require(isinstance(msg, dict), 'invalid_claude_message')
                actor = msg.get('role', typ)
                require(actor == typ, 'invalid_claude_role')
                content = msg.get('content', [])
                if isinstance(content, str):
                    content = [{'type': 'text', 'text': content}]
                require(isinstance(content, list), 'invalid_claude_content')
                for block in content:
                    require(isinstance(block, dict), 'invalid_claude_block')
                    block_type = block.get('type')
                    if block_type == 'text' and isinstance(block.get('text'), str):
                        items.append({'actor': actor, 'kind': 'message', 'text': block['text']})
                    elif block_type == 'tool_use' and actor == 'assistant':
                        args = block.get('input', {})
                        require(isinstance(args, dict), 'invalid_claude_tool')
                        items.append({'actor': actor, 'kind': 'tool_call', 'tool': block.get('name', ''),
                                      'command': args.get('command', args.get('cmd', '')), 'call_id': block.get('id'), 'text': ''})
                    elif block_type == 'tool_result' and actor == 'user':
                        explicit = 'failure' if block.get('is_error') is True else 'success' if block.get('is_error') is False else None
                        items.append({'actor': 'tool', 'kind': 'tool_result', 'call_id': block.get('tool_use_id'),
                                      'outcome': outcome(block.get('content'), explicit), 'text': ''})
                    elif block_type not in {'thinking', 'redacted_thinking', 'image', 'document', 'text'}:
                        raise Fault('unsupported_claude_block')
                session = str(row.get('sessionId', session))
            elif typ not in {'summary', 'system', 'progress', 'file-history-snapshot', 'queue-operation'}:
                raise Fault('unsupported_claude_record')
        if adapter == 'claude':
            # A slash-command record keeps the person's typed arguments; the rest of the wrapper is host context.
            for item in items:
                if item.get('actor') == 'user' and item.get('kind') == 'message' and isinstance(item.get('text'), str) and \
                        item['text'].lstrip().casefold().startswith(('<command-message>', '<command-name>')):
                    args = re.search(r'<command-args>(.*?)</command-args>', item['text'], flags=re.S)
                    if args and args.group(1).strip():
                        item['text'] = args.group(1).strip()
        if adapter in {'codex', 'claude'} and any(
                item.get('actor') == 'user' and item.get('kind') == 'message' and
                isinstance(item.get('text'), str) and item['text'].lstrip().casefold().startswith(INJECTED_PREFIXES)
                for item in items):
            injected_context += 1
            items = [item for item in items if not (item.get('actor') == 'user' and item.get('kind') == 'message')]
        if not items:
            ignored += 1
        for index, item in enumerate(items):
            require(isinstance(item.get('text', ''), str), 'invalid_event_text')
            # Fallback identity is content-derived, never a basename or export position.
            native = item.get('native_id') or raw_id or 'content-' + digest([session, timestamp, item])
            require(isinstance(native, str) and len(native) <= 1000, 'invalid_event_id')
            if len(items) > 1:
                native += ':' + str(index)
            if item['kind'] in {'tool_call', 'tool_result'}:
                text(item.get('call_id'), 500)
            events.append(dict(item, native_id=native, session=item.get('session', session),
                               timestamp=timestamp, line=line))
    return events, ignored, injected_context


def classify(event):
    labels = []
    if event['kind'] == 'reported_summary':
        return [event['declared_signal']]
    if event['kind'] == 'tool_call' and event.get('command'):
        labels.append('executed-command')
    if event['kind'] == 'tool_result' and event.get('command') and event['outcome'] == 'failure':
        labels.append('command-failure')
    if event['kind'] == 'message' and event['actor'] == 'user':
        body = event['snippet'].lower()
        rules = (
            ('repeated-task', r'\b(?:please|can you|could you|create|write|build|check|verify|prepare|summarize|analyse|analyze)\b'),
            ('recurring-feedback', r'\b(?:incorrect|wrong|you missed|forgot|instead of|not what|correction|should have|unchecked)\b'),
            ('follow-up-instruction', r'\b(?:also|next|again|before|after|now|remember to)\b'),
            ('repeated-repair', r'\b(?:fix|repair|retry|workaround|broke|broken|fails again|failed again)\b'),
            ('missed-tool', r'\b(?:did not use|didn.t use|forgot to use|missed|should have used)\b.{0,80}\b(?:tool|checker|browser|search|script)\b'),
            ('cost-decision', r'\b(?:cost|budget|price|cheaper|expensive|tokens|latency)\b'),
            ('user-method', r'\b(?:my method|my workflow|use this process|reusable method|when .{1,80},|first .{1,100}then|always .{1,100}before)\b'),
        )
        labels.extend(kind for kind, pattern in rules if re.search(pattern, body))
    return labels


def compile_scan(path):
    manifest, base, zone, begin, finish, redactor = load_manifest(path)
    budgets = manifest['budgets']
    result = {'schema_version': VERSION, 'corpus_id': manifest['corpus_id'],
              'included_classes': sorted(manifest['included_classes']),
              'contract': {'timezone': manifest['window']['timezone'],
                           'privacy_policy_digest': digest(sorted(manifest.get('private_terms', [])))},
              'window': dict(manifest['window'], begin_utc=stamp(begin), end_exclusive_utc=stamp(finish)),
              'budgets': dict(budgets),
              'sources': {}, 'destinations': {}, 'events': {}, 'complete': True,
              'counts': {'outside_window': 0, 'unknown_time': 0, 'quoted_or_empty': 0, 'excluded_class': 0,
                         'linked_duplicates': 0, 'same_identity_duplicates': 0, 'repeated_native_ids': 0,
                         'ignored_records': 0, 'excluded_injected_context': 0, 'unknown_results': 0},
              'diagnostics': [], 'access_reference': redactor.clean(manifest['access']['reference']),
              'limits': ['Heuristic candidates are review topics, not causes or adopted practices.',
                         'Session independence and mirror links are supplied provenance, not authenticated facts.',
                         'Unknown secrets may survive redaction. Human privacy review is required before sharing.',
                         'Only the documented export layouts are decoded; private reasoning and tool payloads are omitted.']}
    transient = []
    observation_fingerprints = {}
    total = 0
    event_count = 0
    path_set = set()
    for is_dest, entries in ((False, manifest['sources']), (True, manifest.get('destinations', []))):
        for src in entries:
            alias = src['alias']
            info = {'alias': alias, 'status': 'unavailable', 'sha256': None}
            target = result['destinations'] if is_dest else result['sources']
            if not is_dest:
                info.update(adapter=src['adapter'], source_class=src['source_class'],
                            lineage_id=ident('l-', src['lineage_id']), session_id=ident('s-', src['session_id']),
                            source_contract_digest=digest({k: v for k, v in src.items() if k not in {'path', 'resolved_path'}}))
            target[alias] = info
            if not is_dest and src['source_class'] not in manifest['included_classes']:
                info['status'] = 'excluded-class'; result['counts']['excluded_class'] += 1
                continue
            try:
                resolved, symlink = selected_path(src['path'], base, src.get('resolved_path'))
                require(resolved not in path_set, 'duplicate_selected_file')
                path_set.add(resolved)
                remaining = budgets['max_total_bytes'] - total
                require(remaining > 0, 'total_byte_budget_exceeded')
                data = snapshot(resolved, min(budgets['max_file_bytes'], remaining))
                total += len(data)
                info.update(sha256=digest(data), bytes=len(data), resolved_target_declared=symlink)
                if is_dest:
                    info['status'] = 'complete'
                    continue
                require(all(len(line) <= budgets['max_line_bytes'] for line in data.splitlines()), 'line_budget_exceeded')
                raw_events, ignored, injected_context = extract(src, data, budgets['max_line_bytes'])
                event_count += len(raw_events)
                require(event_count <= budgets['max_events'], 'event_budget_exceeded')
                result['counts']['ignored_records'] += ignored
                result['counts']['excluded_injected_context'] += injected_context
                seen_ids = {}
                calls = {}
                for raw in raw_events:
                    identity = [src['adapter'], src['lineage_id'], raw['session'], raw['native_id']]
                    eid = ident('e-', identity)
                    fingerprint = digest(raw | {'line': 0})
                    if eid in seen_ids:
                        require(seen_ids[eid] == fingerprint, 'conflicting_native_event_id')
                        result['counts']['repeated_native_ids'] += 1
                        continue
                    seen_ids[eid] = fingerprint
                    raw['_eid'] = eid
                    if raw['kind'] == 'tool_call':
                        key = (raw['session'], raw['call_id'])
                        require(key not in calls, 'duplicate_tool_call_id')
                        calls[key] = raw
                results = {}
                for raw in raw_events:
                    if raw['kind'] == 'tool_result':
                        when = moment(raw['timestamp'], zone)
                        if when is not None and begin <= when < finish:
                            results.setdefault((raw['session'], raw['call_id']), []).append(raw)
                selected = []
                emitted = set()
                for raw in raw_events:
                    eid = raw.get('_eid')
                    if eid is None or eid in emitted:
                        continue
                    emitted.add(eid)
                    instant = moment(raw['timestamp'], zone)
                    if instant is None:
                        result['counts']['unknown_time'] += 1
                        continue
                    if not begin <= instant < finish:
                        result['counts']['outside_window'] += 1
                        continue
                    snippet = redactor.clean(unquoted(raw.get('text', '')))[:600]
                    if raw['kind'] == 'message' and not snippet:
                        result['counts']['quoted_or_empty'] += 1
                        continue
                    event = {'id': eid, 'source_alias': alias, 'source_sha256': info['sha256'],
                             'adapter': src['adapter'], 'source_class': src['source_class'],
                             'session_id': ident('s-', [src['adapter'], src['lineage_id'], raw['session']]),
                             'context_id': ident('s-', [src['lineage_id'], raw['session']]),
                             'context_type': 'declared-project' if src['adapter'] == 'design' else 'declared-session',
                             'native_id': ident('n-', raw['native_id']), 'line': raw['line'],
                             'timestamp': stamp(instant), 'actor': raw['actor'], 'kind': raw['kind'],
                             'snippet': snippet, 'outcome': 'not-applicable', 'mirrors': []}
                    if raw['kind'] == 'reported_summary':
                        event.update(declared_signal=raw['declared_signal'], origin_fingerprint=raw['origin_fingerprint'],
                                     provenance='supplied-summary-not-direct-observation')
                    if raw['kind'] in {'tool_call', 'tool_result'}:
                        event['call_id'] = ident('c-', [src['adapter'], src['lineage_id'], raw['session'], raw['call_id']])
                        call = raw if raw['kind'] == 'tool_call' else calls.get((raw['session'], raw['call_id']))
                        event['command'] = redactor.clean(command_name(call.get('tool'), call.get('command'))) if call else None
                        event['outcome'] = raw.get('outcome', 'unknown')
                        if raw['kind'] == 'tool_call':
                            matched = results.get((raw['session'], raw['call_id']), [])
                            observed = {x.get('outcome', 'unknown') for x in matched if moment(x['timestamp'], zone) >= instant}
                            if len(observed) == 1:
                                event['outcome'] = observed.pop()
                        event['matching_call_observed'] = call is not None
                        if raw['kind'] == 'tool_result' and not call:
                            result['counts']['unknown_results'] += 1
                    if event['kind'] == 'message' and event['actor'] == 'user' and src['source_class'] in {'subagent', 'automation'}:
                        event['actor'] = 'delegated' if src['source_class'] == 'subagent' else 'automated'
                        event['provenance'] = 'declared-' + src['source_class'] + '-export'
                    event['signals'] = classify(event)
                    observed_record = {key: value for key, value in raw.items() if key not in {'line', '_eid', 'timestamp'}}
                    observed_record['timestamp'] = stamp(instant)
                    observed_record['declared_source_class'] = src['source_class']
                    observed_record['attributed_actor'] = event['actor']
                    observation_fingerprints[(alias, eid)] = digest(observed_record)
                    selected.append((src, raw['native_id'], event))
                transient.extend(selected)
                info['status'] = 'complete'
            except Fault as exc:
                result['complete'] = False
                info['status'] = 'partial-or-unavailable'
                result['diagnostics'].append({'source_alias': alias, 'code': exc.code})
    # A declared native identity is global to its lineage, not local to an export file.
    grouped = {}
    for src, native, event in transient:
        grouped.setdefault(event['id'], []).append((src, native, event))
    conflicting_aliases = set()
    for eid, copies in grouped.items():
        if len({observation_fingerprints[(src['alias'], eid)] for src, _, _ in copies}) > 1:
            conflicting_aliases.update(src['alias'] for src, _, _ in copies)
    for alias in sorted(conflicting_aliases):
        result['complete'] = False
        result['diagnostics'].append({'source_alias': alias, 'code': 'cross_source_id_conflict'})
    admitted = [item for item in transient if item[0]['alias'] not in conflicting_aliases]
    all_events = {}
    transient = []
    for src, native, event in sorted(admitted, key=lambda item: (item[2]['id'], item[0]['alias'], item[2]['line'])):
        if event['id'] in all_events:
            all_events[event['id']]['mirrors'].append({'source_alias': src['alias'], 'native_id': event['native_id'],
                'source_sha256': event['source_sha256'], 'relationship': 'same-native-identity'})
            result['counts']['same_identity_duplicates'] += 1
        else:
            all_events[event['id']] = event
            transient.append((src, native, event))
    # Linked mirrors may target any agreeing copy, even when that copy is not primary.
    lookup = {(src['alias'], native): all_events[event['id']] for src, native, event in admitted}
    parents = {}
    for src, native, event in transient:
        links = {link['event_id']: link for link in src.get('mirrors', [])}
        if native in links:
            link = links[native]
            target = lookup.get((link['source_alias'], link['target_event_id']))
            if target is not None and target['id'] == event['id'] and link['source_alias'] != src['alias']:
                continue  # Already deduplicated as an agreeing copy of this native identity.
            if target is None or target['id'] == event['id']:
                result['complete'] = False
                result['diagnostics'].append({'source_alias': src['alias'], 'code': 'unresolved_mirror'})
                parents[event['id']] = None
            elif (target['actor'], target['kind'], target['snippet'], target.get('command'), target['outcome']) != (event['actor'], event['kind'], event['snippet'], event.get('command'), event['outcome']):
                result['complete'] = False
                result['diagnostics'].append({'source_alias': src['alias'], 'code': 'conflicting_mirror'})
                parents[event['id']] = None
            else:
                parents[event['id']] = target['id']
    invalid_aliases = {d['source_alias'] for d in result['diagnostics'] if d['source_alias'] in result['sources']}
    for eid, event in all_events.items():
        current, visited = eid, set()
        while current in parents and current not in visited:
            visited.add(current); current = parents[current]
        if current is None or current in visited or current not in all_events:
            invalid_aliases.add(event['source_alias'])
            result['complete'] = False
            result['diagnostics'].append({'source_alias': event['source_alias'], 'code': 'invalid_mirror_chain'})
            continue
        if current != eid:
            all_events[current]['mirrors'].append({'source_alias': event['source_alias'], 'native_id': event['native_id'],
                                                   'source_sha256': event['source_sha256']})
            all_events[current]['mirrors'].extend(event['mirrors'])
            result['counts']['linked_duplicates'] += 1
        else:
            result['events'][eid] = event
    for alias in invalid_aliases:
        result['sources'][alias]['status'] = 'partial-or-unavailable'
    result['events'] = {k: v for k, v in result['events'].items() if v['source_alias'] not in invalid_aliases}
    for event in result['events'].values():
        event['record_digest'] = digest(event)
    result['counts']['included_events'] = len(result['events'])
    result['counts']['selected_bytes'] = total
    result['counts']['declared_sessions'] = len({x['session_id'] for x in result['events'].values()})
    result['coverage_complete'] = result['complete'] and result['counts']['unknown_time'] == 0
    result['candidates'] = candidates(result['events'])
    result['scope_id'] = ident('scope-', [result['corpus_id'], result['contract'], result['window'], sorted(result['sources'])])
    return redactor.clean(result), redactor, path_set


def candidates(events):
    groups = {}
    for event in events.values():
        for kind in event['signals']:
            # Exact normalized text/command only. Semantic merging belongs to review.
            normalized = re.sub(r'[^a-z0-9\[\] ]+', ' ', event.get('command') or event['snippet'].lower())
            normalized = ' '.join(normalized.split())
            key = (kind, normalized)
            groups.setdefault(key, []).append(event)
    result = []
    for (kind, normalized), members in sorted(groups.items()):
        sessions = len({x['context_id'] for x in members})
        overlapping = []
        by_instant = {}
        for member in members:
            by_instant.setdefault((member['timestamp'], member['actor'], member['kind']), []).append(member)
        for simultaneous in by_instant.values():
            if len({x['source_alias'] for x in simultaneous}) > 1:
                overlapping.append(sorted(x['id'] for x in simultaneous))
        recurrence = sessions >= 2 and not overlapping
        result.append({'candidate_id': ident('p-', [kind, normalized]), 'signal_class': kind,
                       'observation': (members[0].get('command') or members[0]['snippet'])[:240],
                       'evidence_ids': sorted(x['id'] for x in members), 'event_count': len(members),
                       'declared_session_count': len({x['context_id'] for x in members if x['context_type'] == 'declared-session'}),
                       'declared_context_count': sessions, 'recurrence_supported': recurrence,
                       'possible_unlinked_overlap': overlapping, 'independence': 'declared-provenance-only',
                       'successful_results': sum(x['kind'] == 'tool_call' and x['outcome'] == 'success' for x in members),
                       'confidence': 'unreviewed', 'status': 'review-candidate' if recurrence else 'single-context-observation',
                       'next_review': 'Check the original members, exceptions, existing owner and cause before proposing a change.'})
    return result


def new_book(scan):
    return {'schema_version': VERSION, 'corpus_id': scan['corpus_id'], 'contract': scan['contract'],
            'generation': 0, 'sources': {}, 'destinations': {}, 'events': {}, 'windows': [],
            'last_scan': {}, 'proposals': {}, 'decisions': []}


def evidence_digest(book, ids):
    require(isinstance(ids, list) and ids and len(ids) == len(set(ids)), 'invalid_evidence_members')
    require(all(isinstance(x, str) and x in book['events'] for x in ids), 'missing_evidence_member')
    return digest([book['events'][x] for x in sorted(ids)])


def revision_digest(revision):
    return digest({k: v for k, v in revision.items() if k != 'revision_digest'})


def validate_book(book):
    keys(book, ('schema_version', 'corpus_id', 'contract', 'generation', 'sources', 'destinations', 'events',
                'windows', 'last_scan', 'proposals', 'decisions'))
    require(book['schema_version'] == VERSION and type(book['generation']) is int and book['generation'] >= 0,
            'invalid_casebook')
    slug(book['corpus_id'])
    require(all(isinstance(book[x], dict) for x in ('contract', 'sources', 'destinations', 'events', 'last_scan', 'proposals')),
            'invalid_casebook')
    require(isinstance(book['windows'], list) and isinstance(book['decisions'], list), 'invalid_casebook')
    require(Redactor().clean(book) == book, 'unsafe_casebook_strings')
    for eid, event in book['events'].items():
        require(isinstance(event, dict) and event.get('id') == eid and re.fullmatch(r'e-[0-9a-f]{24}', eid), 'invalid_event_identity')
        require(event.get('record_digest') == digest({k: v for k, v in event.items() if k != 'record_digest'}), 'invalid_event_digest')
        require(event.get('source_alias') in book['sources'], 'invalid_event_source')
        source = book['sources'][event['source_alias']]
        require(source.get('status') == 'complete' and event.get('source_sha256') == source.get('sha256'), 'invalid_event_snapshot')
        require(set(event.get('signals', [])) <= set(KINDS), 'invalid_signal_class')
    for pid, proposal in book['proposals'].items():
        slug(pid); keys(proposal, ('proposal_id', 'revisions'))
        require(proposal['proposal_id'] == pid and isinstance(proposal['revisions'], list) and proposal['revisions'], 'invalid_proposal_identity')
        for i, revision in enumerate(proposal['revisions'], 1):
            keys(revision, ('number', 'proposal', 'evidence_digest', 'revision_digest'))
            require(revision['number'] == i and revision['proposal'].get('proposal_id') == pid, 'invalid_revision_identity')
            require(DIGEST.fullmatch(revision['evidence_digest']) and revision_digest(revision) == revision['revision_digest'], 'invalid_revision_digest')
    previous = None
    for index, decision in enumerate(book['decisions'], 1):
        keys(decision, ('sequence', 'previous_digest', 'record', 'record_digest'))
        record = decision['record']
        keys(record, ('proposal_id', 'revision_digest', 'decision', 'actor_reference', 'decision_reference', 'decided_at', 'scope', 'reason'))
        require(decision['sequence'] == index and decision['previous_digest'] == previous, 'invalid_decision_chain')
        require(digest({k: v for k, v in decision.items() if k != 'record_digest'}) == decision['record_digest'], 'invalid_decision_digest')
        require(record['proposal_id'] in book['proposals'], 'invalid_decision_proposal')
        revisions = book['proposals'][record['proposal_id']]['revisions']
        require(record['revision_digest'] in {x['revision_digest'] for x in revisions}, 'invalid_decision_revision')
        require(record['decision'] in {'approve', 'reject', 'defer', 'revoke', 'supersede'} and record['scope'] == 'handoff-only', 'invalid_decision')
        previous = decision['record_digest']
    return book


def read_book(path):
    book, data, _ = control(path, MAX_CASEBOOK)
    return validate_book(book), digest(data)


def output_path(raw):
    path = Path(os.path.abspath(raw))
    require(not restricted(path), 'restricted_output')
    require(path.parent.exists() and path.parent.is_dir(), 'output_parent_must_exist')
    require(not path.is_symlink(), 'symlink_casebook_forbidden')
    path = path.parent.resolve() / path.name
    require(not restricted(path), 'restricted_output')
    if path.exists():
        require(path.is_file() and path.stat().st_nlink == 1, 'casebook_must_be_single_regular_file')
    return path


class Transaction:
    def __init__(self, path, expected):
        require(expected == 'absent' or DIGEST.fullmatch(expected or ''), 'expected_digest_required')
        self.path, self.expected, self.lock, self.temp = output_path(path), expected, None, None

    def __enter__(self):
        lock = str(self.path) + '.lock'
        try:
            fd = os.open(lock, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            self.lock = lock
            with os.fdopen(fd, 'w') as handle:
                handle.write('Practice Compiler writer lock. Verify no writer is running before manual removal.\n')
            if self.path.exists():
                self.book, actual = read_book(str(self.path))
            else:
                self.book, actual = None, 'absent'
            require(actual == self.expected, 'casebook_digest_conflict')
            return self
        except FileExistsError:
            raise Fault('writer_locked')
        except BaseException:
            if self.lock:
                os.unlink(self.lock); self.lock = None
            raise

    def commit(self, book):
        validate_book(book)
        data = canonical(book) + b'\n'
        require(len(data) <= MAX_CASEBOOK, 'casebook_budget_exceeded')
        # Catch a cooperating stale writer and an out-of-band replacement before commit.
        actual = digest(snapshot(self.path, MAX_CASEBOOK)) if self.path.exists() else 'absent'
        require(actual == self.expected, 'casebook_digest_conflict')
        fd, name = tempfile.mkstemp(prefix='.' + self.path.name + '.', suffix='.tmp', dir=str(self.path.parent))
        self.temp = name
        with os.fdopen(fd, 'wb') as handle:
            handle.write(data); handle.flush(); os.fsync(handle.fileno())
        os.replace(name, self.path); self.temp = None
        try:
            directory = os.open(str(self.path.parent), os.O_RDONLY)
            try:
                os.fsync(directory)
            finally:
                os.close(directory)
        except OSError:
            pass  # Atomic replacement succeeded; directory durability varies by filesystem.
        return digest(data)

    def __exit__(self, *args):
        if self.temp:
            try:
                os.unlink(self.temp)
            except OSError:
                pass
        if self.lock:
            os.unlink(self.lock)


def merge_scan(book, scan, retain_other_sources=False):
    require(book['corpus_id'] == scan['corpus_id'] and book['contract'] == scan['contract'], 'corpus_contract_conflict')
    selected_sources = {alias: src for alias, src in scan['sources'].items() if src['status'] != 'excluded-class'}
    if retain_other_sources:
        combined = dict(book['sources']); combined.update(selected_sources)
    else:
        combined = scan['sources']
    valid = {alias for alias, src in combined.items() if src['status'] == 'complete' and
             book['sources'].get(alias) == src}
    book['events'] = {eid: event for eid, event in book['events'].items() if event['source_alias'] in valid
                      and all(mirror['source_alias'] in valid for mirror in event.get('mirrors', []))}
    book['events'].update(scan['events'])
    book['sources'] = combined
    book['destinations'] = dict(book['destinations'], **scan['destinations']) if retain_other_sources else scan['destinations']
    if scan['window'] not in book['windows']:
        book['windows'].append(scan['window'])
    book['last_scan'] = {k: v for k, v in scan.items() if k not in {'events', 'candidates', 'sources', 'destinations'}}
    book['last_scan']['event_ids'] = sorted(scan['events'])
    book['last_scan']['selected_aliases'] = sorted(scan['sources'])
    book['last_scan']['destination_aliases'] = sorted(scan['destinations'])
    book['last_scan']['checked_aliases'] = sorted(alias for alias, src in scan['sources'].items() if src['status'] == 'complete')
    book['last_scan']['retained_other_sources'] = retain_other_sources
    book['generation'] += 1
    return book


def current_revision(book, pid):
    require(pid in book['proposals'], 'proposal_not_found')
    return book['proposals'][pid]['revisions'][-1]


def proposal_current(book, revision):
    proposal = revision['proposal']
    members = proposal['evidence_ids'] + proposal['counterevidence']['event_ids']
    try:
        current = evidence_digest(book, sorted(set(members))) == revision['evidence_digest']
    except Fault:
        return False
    for artifact in proposal.get('context_artifacts', []):
        snapshot_record = book['destinations'].get(artifact['target_alias'], {})
        current = current and snapshot_record.get('status') == 'complete' and snapshot_record.get('sha256') == artifact['sha256']
    destination = proposal['destination']
    if destination['status'] == 'located':
        src = book['destinations'].get(destination['target_alias'], {})
        current = current and src.get('status') == 'complete' and src.get('sha256') == destination['sha256']
    return current


def latest_decision(book, pid):
    return next((x for x in reversed(book['decisions']) if x['record']['proposal_id'] == pid), None)


def proposal_view(book, pid):
    revision = current_revision(book, pid)
    decision = latest_decision(book, pid)
    state = 'reviewed-awaiting-decision'
    if not proposal_current(book, revision):
        state = 'stale-evidence-or-destination'
    elif decision and decision['record']['revision_digest'] == revision['revision_digest']:
        state = {'approve': 'approval-recorded-currentness-unchecked', 'reject': 'rejected', 'defer': 'deferred',
                 'revoke': 'revoked', 'supersede': 'superseded'}[decision['record']['decision']]
    return {'proposal_id': pid, 'state': state, 'latest_revision': revision, 'latest_decision': decision if decision and decision['record']['revision_digest'] == revision['revision_digest'] else None,
            'consent_authenticated': False, 'applied': False, 'outcome_proved': False}


def reviewed_proposal(record, book, redactor):
    keys(record, ('proposal_id', 'observed_problem', 'evidence_ids', 'diagnosis', 'counterevidence', 'destination',
                  'proposed_change', 'applicability', 'exceptions', 'acceptance_checks', 'privacy_notes', 'review'), ('context_artifacts',))
    slug(record['proposal_id'])
    for field in ('observed_problem', 'applicability', 'exceptions', 'privacy_notes'):
        text(record[field])
    keys(record['diagnosis'], ('category', 'confidence', 'rationale'))
    require(record['diagnosis']['category'] in {'missing-method', 'missed-trigger', 'ignored-guidance', 'broken-tool', 'unresolved', 'verified-resolution'}, 'invalid_diagnosis')
    require(record['diagnosis']['confidence'] in {'low', 'medium', 'high'}, 'invalid_confidence')
    text(record['diagnosis']['rationale'])
    keys(record['counterevidence'], ('event_ids', 'analysis')); text(record['counterevidence']['analysis'])
    require(isinstance(record['counterevidence']['event_ids'], list), 'invalid_counterevidence')
    evidence_digest(book, record['evidence_ids'])
    all_ids = record['evidence_ids'] + record['counterevidence']['event_ids']
    require(all(isinstance(x, str) and x in book['events'] for x in all_ids), 'missing_evidence_member')
    artifacts = record.setdefault('context_artifacts', [])
    require(isinstance(artifacts, list) and len(artifacts) <= 64, 'invalid_context_artifacts')
    artifact_aliases = set()
    for artifact in artifacts:
        keys(artifact, ('target_alias', 'sha256', 'rationale'))
        slug(artifact['target_alias']); text(artifact['rationale'])
        require(artifact['target_alias'] not in artifact_aliases, 'duplicate_context_artifact')
        artifact_aliases.add(artifact['target_alias'])
        snapshot_record = book['destinations'].get(artifact['target_alias'], {})
        require(snapshot_record.get('status') == 'complete' and snapshot_record.get('sha256') == artifact['sha256'],
                'context_artifact_snapshot_mismatch')
    destination = record['destination']
    require(isinstance(destination, dict), 'invalid_destination')
    if destination.get('status') == 'located':
        keys(destination, ('status', 'owner_class', 'target_alias', 'sha256', 'rationale'))
        slug(destination['target_alias']); text(destination['rationale'])
        source = book['destinations'].get(destination['target_alias'], {})
        require(source.get('status') == 'complete' and source.get('sha256') == destination['sha256'], 'destination_snapshot_mismatch')
    else:
        keys(destination, ('status', 'owner_class', 'investigator', 'reason'))
        require(destination['status'] == 'unresolved', 'invalid_destination')
        text(destination['investigator'], 200); text(destination['reason'])
    require(destination['owner_class'] in {'instructions', 'skill', 'tooling', 'workflow', 'documentation', 'unresolved'}, 'invalid_owner_class')
    keys(record['proposed_change'], ('kind', 'text'))
    require(record['proposed_change']['kind'] in {'investigation', 'repair', 'method'}, 'invalid_change_kind')
    if destination['status'] == 'unresolved':
        require(record['proposed_change']['kind'] == 'investigation', 'unlocated_repair_forbidden')
    text(record['proposed_change']['text'])
    checks = record['acceptance_checks']
    require(isinstance(checks, list) and 2 <= len(checks) <= 20, 'acceptance_checks_required')
    for check in checks:
        text(check)
    keys(record['review'], ('reviewer_reference', 'reviewed_at'))
    text(record['review']['reviewer_reference'], 200)
    require(moment(record['review']['reviewed_at'], ZoneInfo('UTC')) is not None and re.search(r'(?:Z|[+-]\d\d:\d\d)$', record['review']['reviewed_at']), 'review_timestamp_requires_offset')
    clean = redactor.clean(record)
    # A changed review must be shown in its redacted form before any decision.
    return clean, digest([book['events'][x] for x in sorted(set(all_ids))])


def book_privacy(path, book):
    manifest, _, _, _, _, redactor = load_manifest(path)
    require(manifest['corpus_id'] == book['corpus_id'] and
            digest(sorted(manifest.get('private_terms', []))) == book['contract']['privacy_policy_digest'],
            'casebook_privacy_policy_mismatch')
    return redactor


class SafeParser(argparse.ArgumentParser):
    def error(self, message):
        raise Fault('invalid_cli_arguments')


def parser():
    p = SafeParser(description=__doc__)
    sub = p.add_subparsers(dest='command', required=True)
    scan = sub.add_parser('scan', help='Read only exact manifest exports. Preview unless --stage is explicit.')
    scan.add_argument('--manifest', required=True)
    scan.add_argument('--stage', action='store_true')
    scan.add_argument('--retain-other-sources', action='store_true', help='Staging only: retain previously admitted omitted/excluded evidence for explicit cumulative use.')
    scan.add_argument('--casebook')
    scan.add_argument('--expected-digest')
    report = sub.add_parser('report', help='Read current or explicit cumulative casebook evidence.')
    report.add_argument('--casebook', required=True)
    report.add_argument('--manifest', required=True, help='The selected manifest supplies the same private redaction policy.')
    report.add_argument('--scope', required=True, choices=('current', 'cumulative'))
    for name in ('revise', 'decide'):
        item = sub.add_parser(name, help='Import a reviewed proposal.' if name == 'revise' else 'Record a declared revision-bound user decision.')
        item.add_argument('--casebook', required=True)
        item.add_argument('--manifest', required=True, help='The selected manifest supplies the same private redaction policy.')
        item.add_argument('--record', required=True)
        item.add_argument('--expected-digest', required=True)
    handoff = sub.add_parser('handoff', help='Recheck evidence and emit an approved handoff-only snapshot, without writes.')
    handoff.add_argument('--casebook', required=True)
    handoff.add_argument('--manifest', required=True)
    handoff.add_argument('--proposal-id', required=True)
    handoff.add_argument('--expected-digest', required=True)
    return p


def run(args):
    redactor = Redactor()
    if args.command == 'scan':
        require(args.stage or not (args.casebook or args.expected_digest or args.retain_other_sources), 'preview_cannot_take_state_arguments')
        require(not args.stage or args.casebook and args.expected_digest, 'staging_arguments_required')
        scan, redactor, paths = compile_scan(args.manifest)
        scan['mode'] = 'staged' if args.stage else 'preview'
        if args.stage:
            require(output_path(args.casebook) not in paths and output_path(args.casebook) != Path(args.manifest).resolve(), 'casebook_overwrites_input')
            with Transaction(args.casebook, args.expected_digest) as tx:
                book = tx.book if tx.book is not None else new_book(scan)
                book = merge_scan(book, scan, args.retain_other_sources)
                # Reapply caller's newly supplied privacy terms to all retained records.
                cleaned = redactor.clean(book)
                require(cleaned == book, 'privacy_change_requires_new_casebook')
                scan['casebook_digest'] = tx.commit(book)
                scan['generation'] = book['generation']
        return scan, 0 if scan['coverage_complete'] else 3, redactor
    if args.command == 'report':
        book, book_digest = read_book(args.casebook)
        redactor = book_privacy(args.manifest, book)
        ids = book['last_scan'].get('event_ids', []) if args.scope == 'current' else list(book['events'])
        events = {eid: book['events'][eid] for eid in ids if eid in book['events']}
        return {'schema_version': VERSION, 'scope': args.scope, 'corpus_id': book['corpus_id'], 'casebook_digest': book_digest,
                'windows': [book['last_scan'].get('window')] if args.scope == 'current' else book['windows'],
                'sources': {alias: source for alias, source in book['sources'].items() if args.scope == 'cumulative' or alias in book['last_scan']['selected_aliases']},
                'source_currentness': {alias: ('checked-in-last-scan' if alias in book['last_scan']['checked_aliases'] else 'stored-not-rechecked') for alias in book['sources'] if args.scope == 'cumulative' or alias in book['last_scan']['selected_aliases']},
                'destinations': {alias: snapshot_record for alias, snapshot_record in book['destinations'].items() if args.scope == 'cumulative' or alias in book['last_scan'].get('destination_aliases', [])}, 'events': events,
                'candidates': candidates(events), 'last_scan': book['last_scan'],
                'reviewed_proposals': [proposal_view(book, pid) for pid in sorted(book['proposals'])
                    if args.scope == 'cumulative' or set(current_revision(book, pid)['proposal']['evidence_ids'] +
                        current_revision(book, pid)['proposal']['counterevidence']['event_ids']) <= set(ids)],
                'decision_history': book['decisions'] if args.scope == 'cumulative' else [],
                'currentness': 'Stored snapshots only. Run handoff with the current manifest before use.'}, 0, redactor
    if args.command in {'revise', 'decide'}:
        record, _, _ = control(args.record)
        with Transaction(args.casebook, args.expected_digest) as tx:
            require(tx.book is not None, 'casebook_not_found')
            book = tx.book
            redactor = book_privacy(args.manifest, book)
            if args.command == 'revise':
                record, member_digest = reviewed_proposal(record, book, redactor)
                pid = record['proposal_id']
                proposal = book['proposals'].setdefault(pid, {'proposal_id': pid, 'revisions': []})
                revision = {'number': len(proposal['revisions']) + 1, 'proposal': record, 'evidence_digest': member_digest}
                revision['revision_digest'] = revision_digest(revision)
                proposal['revisions'].append(revision)
            else:
                keys(record, ('proposal_id', 'revision_digest', 'decision', 'actor_reference', 'decision_reference', 'decided_at', 'scope', 'reason'))
                pid = slug(record['proposal_id'])
                revision = current_revision(book, pid)
                require(record['revision_digest'] == revision['revision_digest'], 'decision_revision_mismatch')
                require(record['decision'] in {'approve', 'reject', 'defer', 'revoke', 'supersede'} and record['scope'] == 'handoff-only', 'invalid_decision')
                for field in ('actor_reference', 'decision_reference', 'reason'):
                    text(record[field], 1000)
                require(moment(record['decided_at'], ZoneInfo('UTC')) is not None and re.search(r'(?:Z|[+-]\d\d:\d\d)$', record['decided_at']), 'decision_timestamp_requires_offset')
                require(record['decision'] != 'approve' or proposal_current(book, revision), 'approval_requires_current_evidence')
                record = redactor.clean(record)
                entry = {'sequence': len(book['decisions']) + 1, 'previous_digest': book['decisions'][-1]['record_digest'] if book['decisions'] else None, 'record': record}
                entry['record_digest'] = digest(entry)
                book['decisions'].append(entry)
            book['generation'] += 1
            result_digest = tx.commit(book)
            return {'casebook_digest': result_digest, 'generation': book['generation'], 'proposal': proposal_view(book, pid),
                    'notice': 'Declared decision records are not authenticated consent. No destination was changed.'}, 0, redactor
    book, book_digest = read_book(args.casebook)
    require(book_digest == args.expected_digest, 'casebook_digest_conflict')
    pid = slug(args.proposal_id)
    revision = current_revision(book, pid)
    decision = latest_decision(book, pid)
    require(proposal_current(book, revision), 'stale_proposal')
    require(decision and decision['record']['revision_digest'] == revision['revision_digest'] and decision['record']['decision'] == 'approve', 'latest_revision_not_approved')
    scan, redactor, _ = compile_scan(args.manifest)
    require(scan['coverage_complete'], 'current_sources_incomplete')
    require(book['corpus_id'] == scan['corpus_id'] and book['contract'] == scan['contract'], 'corpus_contract_conflict')
    proposal = revision['proposal']
    required_aliases = set()
    for eid in proposal['evidence_ids'] + proposal['counterevidence']['event_ids']:
        event = book['events'][eid]
        required_aliases.add(event['source_alias'])
        required_aliases.update(mirror['source_alias'] for mirror in event.get('mirrors', []))
    require(all(alias in scan['sources'] and book['sources'].get(alias) == scan['sources'][alias] for alias in required_aliases),
            'source_snapshots_changed')
    member_ids = set(proposal['evidence_ids'] + proposal['counterevidence']['event_ids'])
    require(member_ids <= set(scan['events']) and all(book['events'][eid]['record_digest'] == scan['events'][eid]['record_digest'] for eid in member_ids),
            'handoff_member_scope_mismatch')
    for artifact in proposal.get('context_artifacts', []):
        snapshot_record = scan['destinations'].get(artifact['target_alias'], {})
        require(snapshot_record.get('status') == 'complete' and snapshot_record.get('sha256') == artifact['sha256'],
                'context_artifact_snapshot_changed')
    dst = proposal['destination']
    if dst['status'] == 'located':
        require(scan['destinations'].get(dst['target_alias'], {}).get('sha256') == dst['sha256'], 'destination_snapshot_changed')
    _, now_digest = read_book(args.casebook)
    require(now_digest == book_digest, 'casebook_changed_during_handoff')
    return {'schema_version': VERSION, 'status': 'handoff-ready',
            'authority': 'investigation-only' if dst['status'] == 'unresolved' else 'proposal-handoff-only',
            'casebook_digest': book_digest, 'proposal_id': pid, 'revision': revision, 'decision': decision,
            'scope': {key: scan[key] for key in ('corpus_id', 'scope_id', 'window', 'included_classes', 'budgets', 'complete', 'coverage_complete', 'counts', 'limits')},
            'evidence': [book['events'][eid] for eid in sorted(set(proposal['evidence_ids'] + proposal['counterevidence']['event_ids']))],
            'receiver_requirements': ['Verify the real user decision through its declared reference.',
                                      'Re-run handoff against the current canonical casebook and selected manifest before acting.',
                                      'Obtain any separate authority needed to inspect or change the destination.'],
            'consent_authenticated': False, 'destination_changed': False, 'applied': False, 'outcome_proved': False}, 0, redactor


def main():
    try:
        args = parser().parse_args()
        result, code, redactor = run(args)
        print(json.dumps(redactor.clean(result), ensure_ascii=True, sort_keys=True, indent=2, allow_nan=False))
        return code
    except Fault as exc:
        print(json.dumps({'status': 'blocked', 'code': exc.code, 'details': 'No raw source content or private paths are included.'}))
        return 2
    except (OSError, ValueError, TypeError, KeyError, AttributeError, RecursionError, OverflowError):
        print(json.dumps({'status': 'blocked', 'code': 'invalid_input_or_io', 'details': 'Check the documented schema, budgets and selected files.'}))
        return 2
    except KeyboardInterrupt:
        print(json.dumps({'status': 'blocked', 'code': 'interrupted'}))
        return 130


if __name__ == '__main__':
    sys.exit(main())
